/**
 * Refresh the GitHub facts of the ecosystem catalogue (MASTER_ROADMAP M10, M19).
 *
 * Which projects are listed, and everything editorial about them (role,
 * relation, layer, maturity), stays hand-curated in src/data/ecosystem.ts
 * after the SAIPEN HQ project map. This script only refreshes what GitHub is
 * the authority for — description, primary language, the release GitHub marks
 * latest, its assets, sizes and the SHA-256 digests GitHub computed — into
 * src/data/ecosystem.snapshot.json, with provenance.
 *
 * Public data only: unauthenticated GitHub REST (two requests per project,
 * well under the 60/hour anonymous limit); GITHUB_TOKEN is used if set.
 * The website itself never calls the network.
 *
 * Usage: npm run ecosystem:sync      Check: npm run validate:ecosystem
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OWNER = 'vacterro';
const SNAPSHOT = 'src/data/ecosystem.snapshot.json';
const MAP = 'https://github.com/saipenhq/.github/blob/main/docs/PROJECTS.md';

/** The curated list, read from the editorial file so there is one list. */
export function curatedRepos(file = 'src/data/ecosystem.ts') {
  return [...readFileSync(file, 'utf8').matchAll(/repo: gh\('([^']+)'\)/g)].map((m) => m[1]);
}

const headers = {
  accept: 'application/vnd.github+json',
  'user-agent': 'sai-website-ecosystem-sync',
  ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
};

async function get(url, allow404 = false) {
  const res = await fetch(url, { headers });
  if (allow404 && res.status === 404) return null;
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status} ${res.statusText}`);
  return res.json();
}

if (process.argv[1]?.endsWith('sync-ecosystem.mjs')) {
  const repos = {};
  for (const name of curatedRepos()) {
    const api = `https://api.github.com/repos/${OWNER}/${name}`;
    const repo = await get(api);
    const latest = await get(`${api}/releases/latest`, true);
    repos[name] = {
      url: repo.html_url,
      queried: api,
      description: repo.description ?? '',
      language: repo.language ?? '—',
      release: latest
        ? {
            tag: latest.tag_name,
            date: latest.published_at.slice(0, 10),
            url: latest.html_url,
            queried: `${api}/releases/latest`,
            assets: latest.assets.map((a) => ({
              name: a.name,
              bytes: a.size,
              sha256: (a.digest ?? '').replace(/^sha256:/, '') || null,
              url: a.browser_download_url,
            })),
          }
        : null,
    };
    console.log(`${name.padEnd(16)} ${latest ? latest.tag_name : '(no latest release)'}`);
  }
  const snapshot = {
    note: 'Generated by scripts/sync-ecosystem.mjs from the public GitHub REST API. Editorial fields live in src/data/ecosystem.ts.',
    snapshot: {
      date: new Date().toISOString().slice(0, 10),
      source: 'GitHub REST API (api.github.com), unauthenticated public data',
      projectMap: MAP,
      owner: OWNER,
    },
    repos,
  };
  writeFileSync(SNAPSHOT, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`wrote ${SNAPSHOT} (${Object.keys(repos).length} repositories)`);
}
