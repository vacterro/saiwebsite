"""
Turn the SAIPEN brand artwork in src/media/ into pixel-law website assets.

The originals are large anti-aliased PNGs (white artwork on transparency).
The site needs Class A pixel art (WINTAGE_WEB_CONTRACT §8, §23): drawn at the
exact size it is displayed, hard 1-bit edges, colour from the active palette.

So each asset is a 1-bit ALPHA MASK at its display size: the original alpha is
resampled once (Lanczos) to the target size and thresholded at 50 %. The page
paints a palette token through the mask (CSS `mask` + `background-color`), so
every mark follows all sixteen themes, carries no colour of its own and never
scales. Only the favicon has a baked colour (Golden Default borderHighlight),
because browser chrome cannot read the page's CSS variables.

Usage: npm run media:build   (python scripts/media/build_media.py)
Deterministic: same sources, same bytes -- but only under the pinned
toolchain in requirements-media.txt (Pillow==12.3.0). The generated
1-bit masks are level-invariant under that pin (verified: compress
levels 6 and 9 emit identical bytes for every approved asset), while
other Pillow/zlib versions may emit different compressed bytes for
identical pixels. Manifest bytes are platform-stable (LF newlines
forced on write). Byte identity is therefore guaranteed only inside
the supported boundary; check_media.py proves the portable properties
(format, dimensions, frame metadata, first-frame pixel identity)
separately from byte hashes. Never hand-edit generated outputs.
"""

from __future__ import annotations

import hashlib
import json
import zlib
from pathlib import Path

import PIL
from PIL import Image

from cosmos_derive import WEBP_DERIVED, derive_webp

# Explicit PNG encoding: no implicit library defaults participate in the
# approved bytes. Level 9 reproduces every currently approved asset
# byte-for-byte under the pinned toolchain (measured, not assumed).
PNG_SAVE_KW = {"optimize": True, "compress_level": 9}

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/media"
OUT = ROOT / "public/media"

# name -> (source file, crop box in source pixels, output width, output height)
ASSETS = {
    "saipen-wordmark-480.png": ("SAIPEN_TEXT1.png", (18, 35, 3616, 648), 480, 82),
    "saipen-wordmark-288.png": ("SAIPEN_TEXT1.png", (18, 35, 3616, 648), 288, 49),
    "saipen-emblem-96.png": ("SAIPEN_design2_alpha.png", (673, 256, 3405, 2965), 96, 96),
    "saipen-emblem-64.png": ("SAIPEN_design2_alpha.png", (673, 256, 3405, 2965), 64, 64),
    "saipen-banner-332.png": ("SAIPEN_design1.png", (251, 295, 3965, 1637), 332, 120),
}
FAVICON = ("favicon-32.png", "__SAIPEN_Alpha.png", (161, 160, 3860, 3859), 32, (0xF0, 0xD0, 0x60))

# Curated full-colour homepage artwork (NOT generated by the 1-bit mask
# pipeline above: these files are checked in as-is and recorded here so
# `media.brand-marks` integrity covers them. The still is the GIF's first
# decoded frame, pixel-for-pixel; scripts/media/check_media.py proves it.
# (name, media_type, width, height, kind, relation)
CURATED = [
    ("saipen-cosmos.gif", "image/gif", 480, 270,
     "curated artwork, animated hero (128 frames, ~8 s, infinite loop)",
     {"still_frame": "saipen-cosmos-still.png"}),
    ("saipen-cosmos-still.png", "image/png", 480, 270,
     "curated artwork, reduced-motion still (first decoded frame, pixel-identical)",
     {"still_of": "saipen-cosmos.gif", "derivation": "first decoded frame of saipen-cosmos.gif"}),
]


def one_bit(source: str, box: tuple[int, int, int, int], width: int, height: int) -> Image.Image:
    alpha = Image.open(SRC / source).getchannel("A").crop(box)
    alpha = alpha.resize((width, height), Image.LANCZOS)
    return alpha.point(lambda v: 255 if v >= 128 else 0)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    records = []
    for name, (source, box, width, height) in ASSETS.items():
        alpha = one_bit(source, box, width, height)
        image = Image.new("LA", (width, height), 255)
        image.putalpha(alpha)
        image.save(OUT / name, **PNG_SAVE_KW)
        records.append({"file": name, "source": f"src/media/{source}", "source_sha256": sha(SRC / source),
                        "crop": list(box), "width": width, "height": height, "kind": "alpha mask",
                        "sha256": sha(OUT / name)})

    name, source, box, size, rgb = FAVICON
    alpha = Image.open(SRC / source).getchannel("A").crop(box).resize((size, size), Image.LANCZOS)
    icon = Image.new("RGBA", (size, size), rgb + (255,))
    icon.putalpha(alpha)
    icon.save(OUT / name, **PNG_SAVE_KW)
    records.append({"file": name, "source": f"src/media/{source}", "source_sha256": sha(SRC / source),
                    "crop": list(box), "width": size, "height": size, "kind": "favicon, Golden Default borderHighlight",
                    "sha256": sha(OUT / name)})

    alpha_16 = Image.open(SRC / source).getchannel("A").crop(box).resize((16, 16), Image.LANCZOS)
    ico_16 = Image.new("RGBA", (16, 16), rgb + (255,))
    ico_16.putalpha(alpha_16)
    icon.save(ROOT / "public/favicon.ico", format="ICO", sizes=[(16, 16), (32, 32)], append_images=[ico_16])

    for name, media_type, width, height, kind, relation in CURATED:
        path = OUT / name
        if not path.exists():
            raise SystemExit(f"missing curated artwork: public/media/{name} (checked-in file required, no external source)")
        with Image.open(path) as probe:
            probe.load()
            actual_format = probe.format
            actual_size = probe.size
        expect_format = "GIF" if media_type == "image/gif" else "PNG"
        if actual_format != expect_format or actual_size != (width, height):
            raise SystemExit(
                f"curated artwork mismatch: public/media/{name} is {actual_format} {actual_size[0]}x{actual_size[1]}, "
                f"expected {expect_format} {width}x{height}")
        records.append({"file": name, "media_type": media_type, "width": width, "height": height,
                        "kind": kind, **relation, "sha256": sha(path)})

    webp_name, webp_source, webp_q, webp_method = WEBP_DERIVED
    webp_path = derive_webp(OUT, webp_name, webp_source, webp_q, webp_method)
    records.append({"file": webp_name, "media_type": "image/webp", "width": 480, "height": 270,
                    "kind": "derived animation, animated WebP (lossy q60, 128 frames, ~8 s, infinite loop)",
                    "derived_from": webp_source, "quality": webp_q, "method": webp_method,
                    "sha256": sha(webp_path)})

    manifest = {
        "note": "SAIPEN brand marks as 1-bit pixel assets. Generated by scripts/media/build_media.py from src/media/ (SAIPEN project artwork). Curated homepage artwork (saipen-cosmos.*) is recorded, never converted.",
        "generator": "scripts/media/build_media.py",
        "assets": records,
        # AUDAPACK manifest closure: the marks are part of the visual evidence.
        "required": [r["file"] for r in records],
    }
    # LF newlines forced: Path.write_text in text mode would translate to
    # the platform default (CRLF on Windows), so manifest bytes would
    # differ between a Windows checkout and Linux CI for identical content.
    with (OUT / "MANIFEST.json").open("w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(manifest, indent=2) + "\n")
    print(f"toolchain: Pillow {PIL.__version__}, zlib {zlib.ZLIB_VERSION} "
          f"(supported pin: requirements-media.txt)")
    for r in records:
        print(f"{r['file']:28} {r['width']}x{r['height']}  {r['kind']}")


if __name__ == "__main__":
    main()
